def map_event_type(raw_type: str) -> str:
    """把 DuEE 细粒度事件类型映射到团队 4 类；无法归类时返回默认类型。"""
    raw_type = (raw_type or "").strip()
    if raw_type in EXPLICIT_TYPE_MAP:
        return EXPLICIT_TYPE_MAP[raw_type]
    for target, keywords in TYPE_RULES:
        if any(k in raw_type for k in keywords):
            return target
    return DEFAULT_EVENT_TYPE


def is_type_covered(raw_type: str) -> bool:
    """判断该事件类型是否能被显式表或关键词规则覆盖（否则会被兜底）。"""
    raw_type = (raw_type or "").strip()
    if raw_type in EXPLICIT_TYPE_MAP:
        return True
    return any(any(k in raw_type for k in keywords) for _, keywords in TYPE_RULES)


